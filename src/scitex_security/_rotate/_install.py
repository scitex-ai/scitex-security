# -*- coding: utf-8 -*-
# File: src/scitex_security/_rotate/_install.py

"""Fleet install of a signed +1-entry manifest (no plaintext leaves the controller).

Each configured host is probed first; a host without the root-owned
trust directory or verifier is SKIPPED with that reason rather than
failed. Hosts listed under ``skipped_hosts`` are reported with their
configured reason and never contacted.
"""

from __future__ import annotations

import shlex
import subprocess
from pathlib import Path
from typing import Dict, List, Sequence

from ._common import Abort, say
from ._settings import RotateSettings

INSTALLER = r"""#!/bin/bash
# Generated by scitex-security rotate-credential. $1 = bundle dir. Prints status/hashes only.
set -uo pipefail
set +x
D="$1"; NEW=__NEW__; OLD=__OLD__; EXP_M=__EXP_M__; EXP_S=__EXP_S__; FPR=__FPR__
T=__TRUST__; VERIFIER=__VERIFIER__; PW=__PW__; OVR=__OVR__
H=$(hostname)
fail() { echo "$H FAIL $*"; exit 1; }
sudo -n true 2>/dev/null || fail "no passwordless sudo"
[ "$(sha256sum "$D/manifest.json" | cut -d' ' -f1)" = "$EXP_M" ] || fail "manifest sha"
[ "$(sha256sum "$D/manifest.json.sig" | cut -d' ' -f1)" = "$EXP_S" ] || fail "sig sha"
cur=$(sha256sum "$T/manifest.json" | cut -d' ' -f1)
if [ "$cur" = "$EXP_M" ]; then echo "$H already installed"; else
  GPGV=$(/usr/bin/python3 -I -c 'import json,sys;print(json.load(open(sys.argv[1]))["gpgv"])' "$T/config.json")
  vs=$("$GPGV" --keyring "$T/issuer.gpg" --status-fd 1 "$D/manifest.json.sig" "$D/manifest.json" 2>/dev/null | awk '$2=="VALIDSIG"{print $NF}')
  [ "$vs" = "$FPR" ] || fail "gpgv VALIDSIG primary=$vs"
  /usr/bin/python3 -I -c '
import json,sys
a=json.load(open(sys.argv[1]));b=json.load(open(sys.argv[2]))
pa=a["payloads"];pb=b["payloads"]
add=set(pb)-set(pa);rm=set(pa)-set(pb);ch=[k for k in set(pa)&set(pb) if pa[k]!=pb[k]]
same={k:v for k,v in a.items() if k!="payloads"}=={k:v for k,v in b.items() if k!="payloads"}
sys.exit(0 if same and add=={sys.argv[3]} and not rm and not ch else 1)' "$T/manifest.json" "$D/manifest.json" "$NEW" || fail "manifest delta is not exactly +1 entry vs installed"
  B=/var/backups/scitex-secrets-$(date -u +%Y%m%dT%H%M%SZ)
  G=$(id -gn root)
  sudo -n install -d -m 700 "$B" && sudo -n cp -p "$T/manifest.json" "$T/manifest.json.sig" "$B/" || fail "backup"
  sudo -n install -o root -g "$G" -m 644 "$D/manifest.json.sig" "$T/manifest.json.sig.new" && \
  sudo -n install -o root -g "$G" -m 644 "$D/manifest.json" "$T/manifest.json.new" && \
  sudo -n mv "$T/manifest.json.new" "$T/manifest.json" && \
  sudo -n mv "$T/manifest.json.sig.new" "$T/manifest.json.sig" || fail "install"
  echo "$H installed (backup $B)"
fi
/usr/bin/python3 -I "$VERIFIER" "$NEW" "$D/$NEW" >/dev/null 2>&1; r1=$?
/usr/bin/python3 -I "$VERIFIER" "$OLD" "$PW/$OLD" >/dev/null 2>&1; r2=$?
if [ $r2 -ne 0 ] && [ -n "${B:-}" ]; then
  sudo -n cp -p "$B/manifest.json" "$B/manifest.json.sig" "$T/" && echo "$H ROLLED BACK (existing payload rc=$r2)"
  exit 1
fi
[ $r1 -eq 0 ] || fail "new payload does not verify (rc=$r1)"
# Ciphertext reaches the payload dir through the dotfiles PR; placing it here would block that pull.
[ -e "$OVR/$OLD" ] && echo "$H WARN host override present for $OLD (rotation will not apply until removed)"
echo "$H RESULT PASS new_payload_rc=$r1 existing_payload_rc=$r2 installed_sha=$(sha256sum "$T/manifest.json" | cut -c1-12)"
"""

#: Marker lines of the readiness probe.
_READY, _MISSING = "SCITEX_TRUST_READY", "SCITEX_TRUST_MISSING"


def shell_path(path: str) -> str:
    """Shell word for ``path``; a leading ``~/`` becomes ``"$HOME"/`` (expanded on the host)."""
    if path == "~":
        return '"$HOME"'
    if path.startswith("~/"):
        return '"$HOME"/' + shlex.quote(path[2:])
    return shlex.quote(path)


def render_installer(
    cfg: RotateSettings, new_name: str, old_name: str, manifest_sha: str, sig_sha: str
) -> str:
    """Per-host installer script with every value shell-quoted."""
    subs = {
        "__NEW__": shlex.quote(new_name),
        "__OLD__": shlex.quote(old_name),
        "__EXP_M__": shlex.quote(manifest_sha),
        "__EXP_S__": shlex.quote(sig_sha),
        "__FPR__": shlex.quote(cfg.issuer_fingerprint),
        "__TRUST__": shell_path(cfg.trust_dir),
        "__VERIFIER__": shell_path(cfg.verifier),
        "__PW__": shell_path(cfg.payload_dir),
        "__OVR__": shell_path(cfg.override_dir),
    }
    out = INSTALLER
    for key, value in subs.items():
        out = out.replace(key, value)
    return out


def readiness_probe(cfg: RotateSettings) -> str:
    """Shell command printing whether the trust directory and verifier exist."""
    return (
        f"if [ -d {shell_path(cfg.trust_dir)} ] && [ -f {shell_path(cfg.verifier)} ]; "
        f"then echo {_READY}; else echo {_MISSING}; fi"
    )


def _ssh(
    host: str, command: str, data: "bytes | None" = None, timeout: float = 300
) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", host, command],
        input=data,
        capture_output=True,
        timeout=timeout,
    )


def _exec(
    cfg: RotateSettings, host: str, command: str, data: "bytes | None" = None
) -> subprocess.CompletedProcess:
    if host == cfg.controller:
        return subprocess.run(
            ["bash", "-c", command], input=data, capture_output=True, timeout=300
        )
    return _ssh(host, command, data=data)


def _install_one(
    cfg: RotateSettings, host: str, work: Path, bundle_name: str, files: Sequence[str]
) -> subprocess.CompletedProcess:
    if host == cfg.controller:
        return subprocess.run(
            ["bash", str(work / "install_on_host.sh"), str(work)],
            capture_output=True,
            timeout=300,
        )
    rdir = shell_path(cfg.runtime_dir.rstrip("/") + "/" + bundle_name)
    if _ssh(host, f"umask 077; mkdir -p {rdir} && chmod 700 {rdir}").returncode:
        raise Abort("mkdir")
    for name in files:
        if _ssh(
            host,
            f"umask 077; cat > {rdir}/{shlex.quote(name)}",
            data=(work / name).read_bytes(),
        ).returncode:
            raise Abort(f"copy {name}")
    return _ssh(host, f"bash {rdir}/install_on_host.sh {rdir}")


def install_all(
    cfg: RotateSettings, work: Path, bundle_name: str, files: Sequence[str]
) -> Dict[str, str]:
    """Install on every configured host; returns ``{host: PASS | FAIL | SKIPPED (reason)}``."""
    results: Dict[str, str] = {}
    for host in cfg.hosts:
        try:
            probe = _exec(cfg, host, readiness_probe(cfg))
            out = probe.stdout.decode(errors="replace")
            if probe.returncode == 0 and _MISSING in out:
                results[host] = f"SKIPPED (no {cfg.trust_dir} trust dir or verifier)"
                say(f"== {host}: {results[host]}")
                continue
            if probe.returncode != 0 or _READY not in out:
                raise Abort(f"readiness probe rc={probe.returncode}")
            proc = _install_one(cfg, host, work, bundle_name, files)
            lines: List[str] = proc.stdout.decode(errors="replace").strip().splitlines()
            say(f"== {host}:", " | ".join(lines[-3:]))
            ok = proc.returncode == 0 and any("RESULT PASS" in line for line in lines)
            results[host] = "PASS" if ok else "FAIL"
        except (Abort, subprocess.TimeoutExpired, OSError) as exc:
            say(f"== {host}: FAIL ({type(exc).__name__}: {exc})")
            results[host] = "FAIL"
    for host, why in cfg.skipped_hosts.items():
        results[host] = f"SKIPPED ({why})"
    return results


